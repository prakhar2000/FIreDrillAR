import test from 'node:test';
import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { randomUUID } from 'node:crypto';
import { setTimeout as delay } from 'node:timers/promises';
import * as THREE from 'three';
import { poseRelay } from './pose-relay.js';
import { createAlignment, alignPose } from '../src/eileen-pose-alignment.js';

test('alignment maps XR floor, translation, yaw and scale into model coordinates', () => {
  const raw = { sessionId: 'session-a', position: [2, 1.6, 4], quaternion: [0, 0, 0, 1] };
  const alignment = createAlignment(raw, new THREE.Vector3(10, 0, 20), 3, 90, 2);
  const first = alignPose(raw, alignment);
  assert.ok(new THREE.Vector3().fromArray(first.position).distanceTo(new THREE.Vector3(10, 6.2, 20)) < 1e-8);
  const next = alignPose({ ...raw, position: [2, 0.9, 3] }, alignment);
  assert.ok(new THREE.Vector3().fromArray(next.position).distanceTo(new THREE.Vector3(12, 4.8, 20)) < 1e-8);
  const forward = new THREE.Vector3(0, 0, -1).applyQuaternion(new THREE.Quaternion().fromArray(next.quaternion));
  assert.ok(forward.distanceTo(new THREE.Vector3(1, 0, 0)) < 1e-8);
  assert.equal(alignPose({ ...raw, sessionId: 'new-session' }, alignment), null);
  assert.throws(() => createAlignment(raw, new THREE.Vector3(), 0, 0, 0));
  const upward = new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(1, 0, 0), Math.PI / 2).toArray();
  assert.throws(() => createAlignment({ ...raw, quaternion: upward }, new THREE.Vector3(), 0));
});

test('relay isolates rooms, rejects invalid/duplicate poses and second publishers, reports disconnects', async () => {
  const ws = new EventEmitter();
  let health;
  poseRelay().configureServer({ ws, middlewares: { use(_path, handler) { health = handler; } }, httpServer: new EventEmitter() });
  const client = () => {
    const socket = new EventEmitter(); socket.readyState = 1; socket.bufferedAmount = 0;
    return { socket, messages: [], send(event, data) { this.messages.push({ event, data }); } };
  };
  const publisher = client(), observer = client(), other = client(), second = client();
  ws.emit('eileen:join', { room: 'test-a', role: 'publisher' }, publisher);
  ws.emit('eileen:join', { room: 'test-a', role: 'observer' }, observer);
  ws.emit('eileen:join', { room: 'test-b', role: 'observer' }, other);
  ws.emit('eileen:join', { room: 'test-a', role: 'publisher' }, second);
  assert.ok(second.messages.some((m) => m.event === 'eileen:error'));
  const pose = { sessionId: randomUUID(), seq: 1, position: [0, 1.6, 0], quaternion: [0, 0, 0, 1] };
  await delay(30);
  ws.emit('eileen:pose', pose, publisher);
  assert.equal(observer.messages.filter((m) => m.event === 'eileen:pose').length, 1);
  assert.equal(other.messages.filter((m) => m.event === 'eileen:pose').length, 0);
  const calibration = { sessionId: pose.sessionId, origin: [0, 0, 0], target: [1, 0, 2], rotation: [0, 0, 0, 1], scale: 1 };
  ws.emit('eileen:alignment', calibration, other);
  assert.equal(publisher.messages.filter((m) => m.event === 'eileen:alignment').length, 0);
  ws.emit('eileen:alignment', { ...calibration, sessionId: 'old-session' }, observer);
  ws.emit('eileen:alignment', { ...calibration, scale: 0 }, observer);
  assert.equal(publisher.messages.filter((m) => m.event === 'eileen:alignment').length, 0);
  ws.emit('eileen:alignment', calibration, observer);
  assert.deepEqual(publisher.messages.at(-1), { event: 'eileen:alignment', data: calibration });
  const marks = { roomId: '10_17_2026', items: [{ type: 'exit', position: [1, 0, 2], source: 'manual' }] };
  ws.emit('eileen:annotations', marks, other);
  ws.emit('eileen:annotations', marks, publisher);
  ws.emit('eileen:annotations', { ...marks, items: [{ type: 'exit', position: [NaN, 0, 0] }] }, observer);
  assert.equal(publisher.messages.filter((m) => m.event === 'eileen:annotations').length, 0);
  ws.emit('eileen:annotations', marks, observer);
  assert.deepEqual(publisher.messages.at(-1).data, marks);
  ws.emit('eileen:annotations', { ...marks, items: [] }, observer);
  assert.deepEqual(publisher.messages.at(-1).data.items, []);
  const effects = { version: 1, roomId: '10_17_2026', running: true, elapsed: 12,
    floorY: 0, ceilingY: 3, center: [0, 0], size: 6, fires: [[1, 0, 1]] };
  ws.emit('eileen:effects', effects, other);
  ws.emit('eileen:effects', effects, publisher);
  ws.emit('eileen:effects', { ...effects, fires: [[Infinity, 0, 0]] }, observer);
  assert.equal(publisher.messages.filter((m) => m.event === 'eileen:effects').length, 0);
  ws.emit('eileen:effects', effects, observer);
  assert.deepEqual(publisher.messages.at(-1), { event: 'eileen:effects', data: effects });
  ws.emit('eileen:effects', { ...effects, running: false, fires: [] }, observer);
  assert.equal(publisher.messages.at(-1).data.running, false);
  assert.deepEqual(publisher.messages.at(-1).data.fires, []);
  await delay(30);
  ws.emit('eileen:pose', pose, publisher);
  ws.emit('eileen:pose', { ...pose, seq: 2, position: [Infinity, 0, 0] }, publisher);
  ws.emit('eileen:pose', { ...pose, seq: 2, quaternion: [0, 0, 0, 0] }, publisher);
  ws.emit('eileen:pose', { ...pose, seq: 2 }, observer);
  ws.emit('eileen:pose', { ...pose, seq: 2, sessionId: 'x'.repeat(65) }, publisher);
  assert.equal(observer.messages.filter((m) => m.event === 'eileen:pose').length, 1);
  ws.emit('eileen:pose', { ...pose, sessionId: 'session-b' }, publisher);
  assert.equal(observer.messages.filter((m) => m.event === 'eileen:pose').length, 2);
  let diagnostics;
  health({}, { setHeader() {}, end(body) { diagnostics = JSON.parse(body); } });
  assert.equal(diagnostics.receivedPoses, 2);
  assert.equal(diagnostics.rooms.find((room) => room.room === 'test-a').observers, 1);
  ws.emit('eileen:tracking', { state: 'lost' }, publisher);
  assert.equal(observer.messages.at(-1).data.state, 'lost');
  publisher.socket.readyState = 3; publisher.socket.emit('close');
  assert.equal(observer.messages.at(-1).data.state, 'disconnected');
  ws.emit('eileen:join', { room: 'test-a', role: 'publisher' }, second);
  assert.equal(second.messages.at(-1).event, 'eileen:joined');
});
